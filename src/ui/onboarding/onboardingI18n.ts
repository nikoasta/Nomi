export type OnboardingI18nKey = keyof (typeof onboardingTranslations)['zh-CN']

export function onboardingTranslate(locale: SupportedLocale, key: OnboardingI18nKey, params?: Record<string, string | number>): string {
  const template = onboardingTranslations[locale][key] ?? onboardingTranslations['zh-CN'][key] ?? key
  if (!params) return template
  return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined || value === null ? match : String(value)
  })
}
